"""Write HData.lean: HOL4's model and statement data for slab C, read from the .d3 file HOL4's kernel loaded.

Usage: python3 -I gen_hdata.py <path to hol4/delta3/slabC.d3> > HData.lean
Each section is copied row by row as written (no reduction, no reordering); only the Lean syntax is added.
"""
import hashlib, sys
path = sys.argv[1]
raw = open(path, 'rb').read()
sec, cur = {}, None
for line in raw.decode().split('\n'):
    if line.startswith('@'):
        cur = line[1:].split()[0]; sec[cur] = []
    elif cur is not None and line.strip():
        sec[cur].append(line.split())
def chunked(name, ty, rows, fmt, size=400):
    out, parts = [], []
    for k in range(0, len(rows), size):
        nm = f'{name}{k // size}'
        parts.append(nm)
        out.append(f'def {nm} : List ({ty}) := [' + ', '.join(fmt(r) for r in rows[k:k + size]) + ']')
    out.append(f'def {name} : List ({ty}) := ' + ' ++ '.join(parts))
    return '\n'.join(out)
print('/- GENERATED by gen_hdata.py from slabC.d3 (sha256 %s, %d bytes): HOL4\'s data for slab C,' % (hashlib.sha256(raw).hexdigest(), len(raw)))
print('   sections @grid @ab @cut @full @theta, each row as written. Core Lean only. -/')
print('def hGrid : List Nat := [' + ', '.join(sec['grid'][0]) + ']')
print(chunked('hAB', 'Int × Nat × Int × Nat', sec['ab'], lambda r: f'({r[0]}, {r[1]}, {r[2]}, {r[3]})'))
print(chunked('hCut', 'Nat × Nat × Int × Nat × Nat', sec['cut'], lambda r: f'({r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]})'))
print(chunked('hFull', 'Nat × Nat × Int', sec['full'], lambda r: f'({r[0]}, {r[1]}, {r[2]})'))
print(chunked('hTheta', 'Int × Nat', sec['theta'], lambda r: f'({r[0]}, {r[1]})'))
s = sec['scal'][0]
print('/-- @scal: lo, hi, B, eps, claim, each (num, den) as written. -/')
print('def hScal : List (Int × Nat) := [' + ', '.join(f'({s[2*k]}, {s[2*k+1]})' for k in range(5)) + ']')
